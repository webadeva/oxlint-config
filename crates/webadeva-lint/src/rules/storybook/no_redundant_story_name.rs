//! `storybook/no-redundant-story-name`: a story should not have a redundant
//! name property.

use oxc_ast::AstKind;
use oxc_ast::ast::{Expression, MemberExpression, ModuleDeclaration, ObjectPropertyKind};

use super::csf::story_name_from_export;
use super::{
    estree_parent, exported_first_var, ident_name, is_stories_file, key_ident_name, string_literal,
};
use crate::rule::{Ctx, Rule};

pub struct NoRedundantStoryName;

const MESSAGE: &str = "Named exports should not use the name annotation if it is redundant to the name that would be generated by the export name";

impl Rule for NoRedundantStoryName {
    fn name(&self) -> &'static str {
        "storybook/no-redundant-story-name"
    }

    fn applies_to(&self, rel_path: &str) -> bool {
        is_stories_file(rel_path)
    }

    fn run<'a>(&self, ctx: &mut Ctx<'a>) {
        // CSF3: `export const Primary = { name: 'Primary' }`.
        for stmt in &ctx.program.body {
            let Some(ModuleDeclaration::ExportDeclaration(export)) = stmt.as_module_declaration()
            else {
                continue;
            };
            let Some((id, Some(init))) = exported_first_var(&export.declaration) else {
                continue;
            };
            let Expression::ObjectExpression(obj) = init.without_parentheses() else {
                continue;
            };
            let story_name = obj.properties.iter().find_map(|p| match p {
                ObjectPropertyKind::ObjectProperty(p)
                    if matches!(key_ident_name(&p.key), Some("name" | "storyName")) =>
                {
                    Some(p)
                }
                _ => None,
            });
            let Some(story_name) = story_name else {
                continue;
            };
            if string_literal(&story_name.value)
                .is_some_and(|v| v == story_name_from_export(&id.name))
            {
                ctx.report(story_name.span, MESSAGE);
            }
        }

        // CSF2: `Primary.storyName = 'Primary'`.
        let nodes = ctx.semantic.nodes();
        for node in nodes.iter() {
            let AstKind::AssignmentExpression(assign) = node.kind() else {
                continue;
            };
            if !estree_parent(nodes, node.id())
                .is_some_and(|p| matches!(nodes.kind(p), AstKind::ExpressionStatement(_)))
            {
                continue;
            }
            let Some(member) = assign.left.as_member_expression() else {
                continue;
            };
            let property = match member {
                MemberExpression::StaticMemberExpression(m) => Some(m.property.name.as_str()),
                MemberExpression::ComputedMemberExpression(m) => ident_name(&m.expression),
                MemberExpression::PrivateFieldExpression(_) => None,
            };
            if property != Some("storyName") {
                continue;
            }
            let Some(object) = ident_name(member.object()) else {
                continue;
            };
            if string_literal(&assign.right).is_some_and(|v| v == story_name_from_export(object)) {
                ctx.report(assign.span, MESSAGE);
            }
        }
    }
}
